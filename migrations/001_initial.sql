CREATE TABLE IF NOT EXISTS schema_migrations (
    version VARCHAR(64) PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL CHECK (role IN ('network_engineer', 'noc_supervisor', 'system_admin')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    failed_login_attempts INTEGER NOT NULL DEFAULT 0 CHECK (failed_login_attempts >= 0),
    locked_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS towers (
    tower_id VARCHAR(64) PRIMARY KEY,
    region VARCHAR(128) NOT NULL,
    latitude DOUBLE PRECISION CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    netconf_host VARCHAR(255),
    netconf_port INTEGER NOT NULL DEFAULT 830 CHECK (netconf_port BETWEEN 1 AND 65535),
    yang_profile VARCHAR(128),
    hardware_status VARCHAR(32) NOT NULL DEFAULT 'unknown',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS kpi_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tower_id VARCHAR(64) NOT NULL REFERENCES towers(tower_id) ON DELETE CASCADE,
    timestamp TIMESTAMPTZ NOT NULL,
    connected_users INTEGER NOT NULL CHECK (connected_users >= 0),
    prb_usage_pct DOUBLE PRECISION NOT NULL CHECK (prb_usage_pct BETWEEN 0 AND 100),
    throughput_mbps DOUBLE PRECISION NOT NULL CHECK (throughput_mbps >= 0),
    latency_ms DOUBLE PRECISION NOT NULL CHECK (latency_ms >= 0),
    call_drop_rate_pct DOUBLE PRECISION NOT NULL CHECK (call_drop_rate_pct BETWEEN 0 AND 100),
    handover_failure_rate_pct DOUBLE PRECISION NOT NULL CHECK (handover_failure_rate_pct BETWEEN 0 AND 100),
    hardware_status VARCHAR(32) NOT NULL,
    source VARCHAR(64) NOT NULL DEFAULT 'nms',
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_kpi_tower_timestamp UNIQUE (tower_id, timestamp)
);
CREATE INDEX IF NOT EXISTS ix_kpi_timestamp ON kpi_metrics (timestamp);
CREATE INDEX IF NOT EXISTS ix_kpi_tower_timestamp ON kpi_metrics (tower_id, timestamp);

CREATE TABLE IF NOT EXISTS fault_events (
    id UUID PRIMARY KEY,
    external_id VARCHAR(255) UNIQUE,
    tower_id VARCHAR(64) NOT NULL REFERENCES towers(tower_id) ON DELETE CASCADE,
    occurred_at TIMESTAMPTZ NOT NULL,
    cleared_at TIMESTAMPTZ,
    severity VARCHAR(32) NOT NULL,
    alarm_code VARCHAR(128) NOT NULL,
    description TEXT NOT NULL,
    raw_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    source VARCHAR(64) NOT NULL DEFAULT 'nms'
);
CREATE INDEX IF NOT EXISTS ix_fault_tower_occurred ON fault_events (tower_id, occurred_at);
CREATE INDEX IF NOT EXISTS ix_fault_severity_status ON fault_events (severity, cleared_at);

CREATE TABLE IF NOT EXISTS optimization_actions (
    id UUID PRIMARY KEY,
    tower_id VARCHAR(64) NOT NULL REFERENCES towers(tower_id) ON DELETE RESTRICT,
    action_type VARCHAR(64) NOT NULL CHECK (action_type IN ('ret_adjustment', 'load_balancing')),
    parameters JSONB NOT NULL,
    status VARCHAR(32) NOT NULL CHECK (status IN (
        'pending_approval', 'approved', 'executing', 'pending_confirmation',
        'confirmed', 'rejected', 'failed', 'reverted', 'confirmation_failed'
    )),
    created_by VARCHAR(100) NOT NULL,
    approved_by VARCHAR(100),
    executed_by VARCHAR(100),
    netconf_message_id VARCHAR(255),
    failure_detail TEXT,
    confirmation_deadline TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_actions_status_created ON optimization_actions (status, created_at);
CREATE INDEX IF NOT EXISTS ix_actions_tower_created ON optimization_actions (tower_id, created_at);

CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(100) NOT NULL,
    event_type VARCHAR(128) NOT NULL,
    resource_type VARCHAR(64) NOT NULL,
    resource_id VARCHAR(255) NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_audit_created ON audit_logs (created_at);
CREATE INDEX IF NOT EXISTS ix_audit_actor_created ON audit_logs (actor, created_at);
